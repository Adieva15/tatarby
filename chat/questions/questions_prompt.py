
AGE_HUMAN = {
    "child_7_10": "ребёнок 7–10 лет",
    "teen_11_15": "подросток 11–15 лет",
    "adult_16_plus": "взрослый",
}

LEVEL_HUMAN = {
    "A1": "A1 — начинающий",
    "A2": "A2 — элементарный",
    "B1": "B1 — средний",
    "B2": "B2 — выше среднего",
    "C1": "C1 — продвинутый",
}


def build_questions_prompt(text: str, age_group: str, level: str, n: int = 5) -> str:
    return f"""# ЗАДАЧА
Составь ровно {n} вопросов на понимание текста.

# АУДИТОРИЯ
- Возраст: {AGE_HUMAN.get(age_group, age_group)}
- Уровень русского: {LEVEL_HUMAN.get(level, level)}

# ПРАВИЛА
- Вопросы на русском, в рамках уровня {level}.
- К каждому вопросу РОВНО 4 варианта ответа.
- Ровно один правильный — укажи его буквой: "A", "B", "C" или "D".
- Неправильные варианты должны быть похожи на правду, но противоречить тексту.
- difficulty — сложность вопроса от 1 до 5, где 1 — очень просто, 5 — очень сложно.
- Не спрашивай то, чего нет в тексте.

# ФОРМАТ ОТВЕТА (строго JSON)
{{
  "questions": [
    {{
      "text": "текст вопроса",
      "option_a": "первый вариант",
      "option_b": "второй вариант",
      "option_c": "третий вариант",
      "option_d": "четвёртый вариант",
      "correct_option": "A",
      "difficulty": 2
    }}
  ]
}}

# ТЕКСТ
{text}
"""