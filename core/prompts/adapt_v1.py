# core/prompts/adapt_v1.py
from core.schemas import AdaptRequest

AGE_HUMAN = {
    "child_7_10": "ребёнок 7–10 лет",
    "teen_11_15": "подросток 11–15 лет",
    "adult_16_plus": "взрослый читатель",
}

STYLE_HUMAN = {
    "simple": "по-простому, короткими предложениями",
    "poetic": "поэтично, с образами и ритмом",
    "prose": "прозаично, плавным повествованием",
    "academic": "академически, точно и формально",
}

LEVEL_RULES = {
    "A1": "топ-1000 частотных слов, предложения до 7 слов",
    "A2": "топ-2000 слов, предложения до 10 слов",
    "B1": "топ-5000 слов, сложные предложения допустимы",
    "B2": "сохраняй сложность оригинала, меняй только стиль",
    "C1": "сохраняй оригинал, адаптируй только лексические нюансы",
}


def build_adapt_prompt(req: AdaptRequest) -> str:
    p = req.profile
    return f"""# РОЛЬ
Ты — редактор-адаптер русского текста для читателей с разным уровнем языка.

# ПРОФИЛЬ ЧИТАТЕЛЯ
- Возраст: {AGE_HUMAN[p.age_group]}
- Уровень русского (CEFR): {p.language_level}
- Желаемый стиль: {STYLE_HUMAN[p.preferred_style]}
- Родной язык: {p.native_language}

# ЗАДАЧА
Перепиши текст ниже так, чтобы он подходил этому читателю.

# ПРАВИЛА ДЛЯ УРОВНЯ {p.language_level}
- {LEVEL_RULES[p.language_level]}
- Сохрани 100% исходного смысла.
- Не добавляй факты, которых не было в оригинале.

# ЗАПРЕТЫ
- Не писать вводные фразы («Вот текст...», «Конечно!»).
- Не добавлять объяснения от себя.
- Не возвращать ничего, кроме JSON.

# ФОРМАТ ОТВЕТА (строго JSON)
{{
  "adapted_text": "строка",
  "difficulty_score": 0.0,
  "vocabulary_notes": [
    {{"original": "...", "replacement": "...", "reason": "..."}}
  ]
}}

# ТЕКСТ
{req.russian_text}
"""